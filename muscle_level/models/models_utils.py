class Adaptive_Spectral_Block(nn.Module):
    def __init__(self, dim=1):
        super().__init__()
        self.complex_weight_high = nn.Parameter(torch.randn(dim, 2, dtype=torch.float32) * 0.02)
        self.complex_weight = nn.Parameter(torch.randn(dim, 2, dtype=torch.float32) * 0.02)
        trunc_normal_(self.complex_weight_high, std=.02)
        trunc_normal_(self.complex_weight, std=.02)
        self.threshold_param = nn.Parameter(torch.rand(1)) # * 0.5)
        
    def _compute_adaptive_mask(self, energy, shape):
        """Compute adaptive mask from energy tensor based on shape"""
        if len(shape) == 3:  # B, C, W
            B = shape[0]
            # Flatten energy across C and W dimensions and then compute median
            flat_energy = energy.view(B, -1)
            median_energy = flat_energy.median(dim=1, keepdim=True)[0]
            median_energy = median_energy.view(B, 1)
        elif len(shape) == 4:  # B, num_instances, C, W
            B, num_instances = shape[0], shape[1]
            # Flatten across instances for median calculation
            flat_energy = energy.view(B, num_instances, -1)
            median_energy = flat_energy.median(dim=2, keepdim=True)[0]
            median_energy = median_energy.view(B, num_instances, 1)
        
        # Normalize energy and create adaptive mask
        epsilon = 1e-6
        normalized_energy = energy / (median_energy + epsilon)
        adaptive_mask = ((normalized_energy > self.threshold_param).float() - self.threshold_param).detach() + self.threshold_param
        return adaptive_mask.unsqueeze(-1)  # Add frequency dimension back

    # def create_adaptive_high_freq_mask(self, x_fft):
    #     """Create adaptive high frequency mask from FFT result"""
    #     shape = x_fft.shape
    #     # Calculate energy in the frequency domain
    #     energy_freq_dim = -1 if len(shape) == 3 else -1  # Both cases sum over the last dimension (frequency)
    #     energy = torch.abs(x_fft).pow(2).sum(dim=energy_freq_dim)
    #     return self._compute_adaptive_mask(energy, shape)

    def create_adaptive_high_freq_mask(self, x_fft):
        P = torch.abs(x_fft).pow(2)
        binary_mask = (P > self.threshold_param).float()
        adaptive_mask = (binary_mask - self.threshold_param).detach() + self.threshold_param
        return adaptive_mask
    
    def _apply_spectral_transform(self, x, time_dim, W, original_shape):
        """Apply spectral transformation operations"""
        # Apply FFT along the time dimension
        x_fft = torch.fft.rfft(x, dim=time_dim, norm='ortho')
        weight = torch.view_as_complex(self.complex_weight)
        x_weighted = x_fft * weight
        
        # Adaptive High Frequency Mask
        freq_mask = self.create_adaptive_high_freq_mask(x_fft)
        x_masked = x_fft * freq_mask.to(x.device)
        weight_high = torch.view_as_complex(self.complex_weight_high)
        x_weighted2 = x_masked * weight_high
        x_weighted += x_weighted2
        
        # Apply Inverse FFT
        x = torch.fft.irfft(x_weighted, n=W, dim=time_dim, norm='ortho')
        x = x.view(original_shape)  # Reshape back to original shape
        
        # Compute frequency features
        len_f = int(0.5 * W)
        x_f = torch.abs(x_weighted[..., :len_f])
        
        return x, x_f

    def forward(self, x_in):
        shape = x_in.shape
        dtype = x_in.dtype
        x = x_in.to(torch.float32)
        
        if len(shape) == 3:  # B, C, W
            _, _, W = shape
            x, x_f = self._apply_spectral_transform(x, time_dim=2, W=W, original_shape=shape)
            x = x.to(dtype)
            
        elif len(shape) == 4:  # B, num_instances, C, W
            _, _, _, W = shape
            x, x_f = self._apply_spectral_transform(x, time_dim=3, W=W, original_shape=shape)
            x = x.to(dtype)
        
        return x, x_f



